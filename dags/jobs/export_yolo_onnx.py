"""Stage 5 — EXPORT + DEPLOY (CUDA): trained YOLO weights -> ONNX -> Triton.

Runs in the GPU job image (torch needed for the export). Mirrors the platform
`deploy_model.py` pattern, which was validated against the 26.07 server:

* Triton 26.x repo layout: `config.pbtxt` lives at the MODEL ROOT
  (`triton-models/<name>/config.pbtxt`) — a config inside the version dir is
  silently ignored. With `max_batch_size > 0` the batch dim is implicit, so
  config dims carry only the non-batch dims (e.g. input [3,640,640], not
  [0,3,640,640]).
* Explicit model control goes over gRPC (the 26.07 HTTP `.../load` endpoint
  404s): `get_model_repository_index` / `unload_model` / `load_model` /
  `is_model_ready` via `tritonclient.grpc`.
* After load, verify the staged config actually took effect (server returns
  `max_batch_size == MAX_BATCH_SIZE` from `GET /v2/models/<name>/config`);
  otherwise re-index + reload (guards against a stale/auto-completed config).

Artifacts: model.onnx + config.pbtxt -> s3://<bucket>/models/<run_id>/yolo/,
model_info.json -> S3 AND at the model root (consumed by the standalone
inference test script), manifest -> s3://<bucket>/data/<run_id>/.
"""
from __future__ import annotations

import json
import os
import sys
import time

import boto3
import onnx
import requests
from onnx import TensorProto
from tritonclient import grpc as gc
from ultralytics import YOLO

# --- env ---------------------------------------------------------------------
S3_ENDPOINT = os.environ["S3_ENDPOINT"]
S3_BUCKET = os.environ["S3_BUCKET"]
S3_REGION = os.environ.get("S3_REGION", "us-east-1")
S3_ACCESS = os.environ["S3_ACCESS_KEY"]
S3_SECRET = os.environ["S3_SECRET_KEY"]
RUN_ID = os.environ["RUN_ID"]

TRITON_HTTP_URL = os.environ.get("TRITON_HTTP_URL", "http://triton:8005")
TRITON_GRPC_URL = os.environ.get("TRITON_GRPC_URL", "triton:8000")
TRITON_DET_MODEL = os.environ.get("TRITON_DET_MODEL", "yolo_voc12")
IMGSZ = int(os.environ.get("IMGSZ", "640"))
MAX_BATCH_SIZE = int(os.environ.get("TRITON_MAX_BATCH", "16"))
MODELS_DIR = "/models"  # shared Triton repository bind mount

TYPE_MAP = {TensorProto.FLOAT: "TYPE_FP32", TensorProto.DOUBLE: "TYPE_FP64",
            TensorProto.INT32: "TYPE_INT32", TensorProto.INT64: "TYPE_INT64",
            TensorProto.STRING: "TYPE_STRING"}


def s3_client() -> "boto3.client":
    return boto3.client(
        "s3",
        endpoint_url=S3_ENDPOINT,
        aws_access_key_id=S3_ACCESS,
        aws_secret_access_key=S3_SECRET,
        region_name=S3_REGION,
    )

def dims_of(graph_dim_list) -> list[int]:
    """Graph dims -> config dims. The leading dynamic (batch) dim is dropped
    (implicit via max_batch_size); any other dynamic dim -> 0 (Triton's marker)."""
    dims = []
    for d in graph_dim_list:
        if d.dim_param:                    # dynamic dim (e.g. "batch")
            dims.append(-1)                # Triton flexible-dim marker
        else:
            dims.append(int(d.dim_value))
    if dims and dims[0] == -1:             # Triton: batch is implicit
        dims = dims[1:]
    return dims


def config_text(name: str, in_name: str, in_dims: list, out_name: str, out_dims: list) -> str:
    return f"""# generated by export_yolo_onnx.py (Triton 26.x layout: config at model root)
name: "{name}"
backend: "onnxruntime"
max_batch_size: {MAX_BATCH_SIZE}

input [
  {{
    name: "{in_name}"
    data_type: TYPE_FP32
    dims: [{", ".join(str(d) for d in in_dims)}]
  }}
]
output [
  {{
    name: "{out_name}"
    data_type: TYPE_FP32
    dims: [{", ".join(str(d) for d in out_dims)}]
  }}
]
"""


def stage_and_load(name: str, config: str, onnx_bytes: bytes) -> None:
    """Atomic staging into the shared repo + explicit gRPC model control."""
    import shutil
    model_dir = os.path.join(MODELS_DIR, name)
    version_dir = os.path.join(model_dir, "1")
    os.makedirs(version_dir, exist_ok=True)

    client = gc.InferenceServerClient(url=TRITON_GRPC_URL)

    def refresh_repo() -> None:
        """Full repository re-scan. The tritonclient wrapper hardcodes
        IndexModelRepository(ready=False), which can leave the server's
        repository snapshot stale; call the raw RPC with ready=True."""
        from tritonclient.grpc import service_pb2
        req = service_pb2.RepositoryIndexRequest(ready=True)
        client._client_stub.RepositoryIndex(
            request=req, metadata=client._get_metadata(None), timeout=30)

    def repo_has() -> bool:
        refresh_repo()
        idx = client.get_model_repository_index()
        return name in [m.name for m in idx.models]

    def stage() -> None:
        os.makedirs(version_dir, exist_ok=True)
        for path, data in (
            (os.path.join(model_dir, "config.pbtxt"), config.encode()),
            (os.path.join(version_dir, "model.onnx"), onnx_bytes),
        ):
            tmp = path + ".staging"
            with open(tmp, "wb") as f:
                f.write(data)
                f.flush()
                os.fsync(f.fileno())
            os.replace(tmp, path)

    # If a stale/older version is already indexed or loaded, clear it so the
    # server re-indexes the freshly staged files as a *new* model (under
    # explicit model control a changed model can otherwise sit in a stale
    # repo snapshot and fail with "failed to poll from model repository").
    if repo_has():
        try:
            client.unload_model(name)
        except Exception:
            pass  # not loaded
        shutil.rmtree(model_dir, ignore_errors=True)
        client.get_model_repository_index()  # re-scan: model gone from index
    stage()
    print(f"staged: {model_dir}/config.pbtxt + {version_dir}/model.onnx")

    deadline = time.time() + 60
    loaded = False
    last_err = None
    while not loaded:
        refresh_repo()  # authoritative server-side repo re-scan
        try:
            client.load_model(name)
            loaded = True
        except Exception as e:
            last_err = e
            if time.time() > deadline:
                raise RuntimeError(f"model '{name}' failed to load: {last_err}")
            time.sleep(2)
    deadline = time.time() + 120
    while not client.is_model_ready(name):
        if time.time() > deadline:
            raise RuntimeError(f"model '{name}' did not become ready")
        time.sleep(1)
    print(f"triton model ready: {name} (gRPC {TRITON_GRPC_URL})")

    # Verify the STAGED config is the one in effect (server auto-completes a
    # missing/stale config and would silently pick max_batch_size 4).
    deadline = time.time() + 90
    while True:
        r = requests.get(f"{TRITON_HTTP_URL}/v2/models/{name}/config", timeout=10)
        r.raise_for_status()
        if r.json().get("max_batch_size") == MAX_BATCH_SIZE:
            break
        if time.time() > deadline:
            raise RuntimeError(f"config not in effect for '{name}': {r.text[:400]}")
        print(f"stale config for {name}; re-indexing + reloading ...")
        try:
            client.unload_model(name)
        except Exception:
            pass
        client.get_model_repository_index()
        client.load_model(name)
        deadline = time.time() + 90


def main() -> None:
    s3 = s3_client()

    # --- trained weights from the train stage -------------------------------
    train_manifest = json.loads(s3.get_object(
        Bucket=S3_BUCKET, Key=f"data/{RUN_ID}/yolo_train_manifest.json")["Body"].read())
    pt_key = train_manifest["best_pt"].split(f"s3://{S3_BUCKET}/", 1)[-1]
    pt_local = "/tmp/best.pt"
    s3.download_file(S3_BUCKET, pt_key, pt_local)
    print(f"downloaded weights: s3://{S3_BUCKET}/{pt_key}")

    # --- torch -> ONNX (dynamic batch) --------------------------------------
    model = YOLO(pt_local)
    out = model.export(format="onnx", imgsz=IMGSZ, dynamic=True)
    onnx_path = str(out)
    print(f"exported ONNX: {onnx_path}")

    # --- read the graph to generate the config ------------------------------
    graph = onnx.load(onnx_path).graph
    in_name = graph.input[0].name
    out_name = graph.output[0].name
    in_dims = dims_of(graph.input[0].type.tensor_type.shape.dim)
    out_dims = dims_of(graph.output[0].type.tensor_type.shape.dim)
    in_graph_dims = [ (d.dim_param or d.dim_value or 0) for d in graph.input[0].type.tensor_type.shape.dim ]
    out_graph_dims = [ (d.dim_param or d.dim_value or 0) for d in graph.output[0].type.tensor_type.shape.dim ]
    print(f"graph: {in_name} {in_graph_dims} -> {out_name} {out_graph_dims}; config dims {in_dims}/{out_dims}")

    onnx_bytes = open(onnx_path, "rb").read()
    name = TRITON_DET_MODEL
    config = config_text(name, in_name, in_dims, out_name, out_dims)
    stage_and_load(name, config, onnx_bytes)

    # --- gRPC smoke inference (batch of zeros) ------------------------------
    import numpy as np
    client = gc.InferenceServerClient(url=TRITON_GRPC_URL)
    x = np.zeros((2, 3, IMGSZ, IMGSZ), dtype=np.float32)
    inp = gc.InferInput(in_name, x.shape, "FP32")
    inp.set_data_from_numpy(x)
    resp = client.infer(model_name=name, inputs=[inp])
    y = resp.as_numpy(out_name)
    print(f"smoke infer ok: {y.shape} (via Triton gRPC)")

    # --- publish -------------------------------------------------------------
    run_s3 = f"models/{RUN_ID}/yolo"
    s3.upload_file(onnx_path, S3_BUCKET, f"{run_s3}/model.onnx")
    s3.put_object(Bucket=S3_BUCKET, Key=f"{run_s3}/config.pbtxt", Body=config.encode())

    model_info = {
        "model_name": name,
        "backend": "onnxruntime",
        "max_batch_size": MAX_BATCH_SIZE,
        "input": {"name": in_name, "dims": in_graph_dims},
        "output": {"name": out_name, "dims": out_graph_dims},
        # objectness-free detection head (YOLOv8/11): first non-batch dim = 4 box + nc
        "class_count": out_dims[0] - 4,
        "class_names": train_manifest.get("class_names", []),
        "imgsz": IMGSZ,
        "onnx_s3_key": f"s3://{S3_BUCKET}/{run_s3}/model.onnx",
        "weights_s3_key": f"s3://{S3_BUCKET}/{pt_key}",
    }
    s3.put_object(Bucket=S3_BUCKET, Key=f"{run_s3}/model_info.json",
                  Body=json.dumps(model_info, indent=2).encode())
    # also at the model root so the standalone test script can read it
    with open(os.path.join(MODELS_DIR, name, "model_info.json"), "w") as f:
        json.dump(model_info, f, indent=2)

    manifest = {
        "run_id": RUN_ID,
        "triton_model": name,
        "triton_grpc": TRITON_GRPC_URL,
        "triton_http": TRITON_HTTP_URL,
        "onnx_s3_key": f"s3://{S3_BUCKET}/{run_s3}/model.onnx",
        "model_info_s3": f"s3://{S3_BUCKET}/{run_s3}/model_info.json",
        "max_batch_size": MAX_BATCH_SIZE,
        "input": model_info["input"],
        "output": model_info["output"],
    }
    mkey = f"data/{RUN_ID}/yolo_export_manifest.json"
    s3.put_object(Bucket=S3_BUCKET, Key=mkey, Body=json.dumps(manifest, indent=2).encode())
    print(f"EXPORT OK: '{name}' live on Triton (gRPC {TRITON_GRPC_URL}); manifest {mkey}")


if __name__ == "__main__":
    t0 = time.time()
    main()
    print(f"export_yolo_onnx finished in {time.time() - t0:.1f}s")